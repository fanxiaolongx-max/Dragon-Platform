// Run: ./node_modules/.bin/electron tests/conversation-rail-browser.cjs
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const root = path.join(__dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'conversation-rail-'));
app.setPath('userData', path.join(temp, 'profile'));
app.disableHardwareAcceleration();
let win;
const evaluate = code => win.webContents.executeJavaScript(code, true);
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const timeout = setTimeout(() => app.exit(1), 30000);
app.whenReady().then(async () => {
    win = new BrowserWindow({ show: true, width: 1000, height: 800, webPreferences: { nodeIntegration: false, contextIsolation: true } });
    const css = fs.readFileSync(path.join(root, 'frontend/css/conversation-rail.css'), 'utf8');
    const js = fs.readFileSync(path.join(root, 'frontend/js/home/conversation-rail.js'), 'utf8');
    const fixture = path.join(temp, 'fixture.html');
    fs.writeFileSync(fixture, `<html><style>body{margin:0}#dcThread{position:absolute;left:180px;right:0;top:80px;height:500px;overflow:auto}.dc-msg{height:140px;padding-left:50px}</style><style>${css}</style><body><div id="dcThread"></div><script>window.lang='zh-CN';window.ToolsI18n={getLanguage:()=>window.lang};window.fetch=()=>{throw Error('Navigation must not fetch history')};window.fill=n=>{document.getElementById('dcThread').innerHTML=Array.from({length:n},(_,i)=>'<div class="dc-msg dc-msg--user"><div class="dc-msg-body">Question '+i+' &lt;img src=x&gt;</div></div><div class="dc-msg dc-msg--ai">Answer</div>').join('')};fill(130);</script><script>${js}</script></body></html>`);
    await win.loadFile(fixture); await wait(250);
    assert.equal(await evaluate(`document.querySelectorAll('.conversation-rail button').length`), 100);
    assert.match(await evaluate(`document.querySelector('.conversation-rail button').ariaLabel`), /Question 30/);
    assert.equal(await evaluate(`document.querySelector('.conversation-rail').hidden`), false);
    await evaluate(`document.querySelector('.conversation-rail button').focus()`);
    assert.equal(await evaluate(`document.querySelector('.conversation-rail-preview img')`), null);
    assert.equal(await evaluate(`document.querySelector('.conversation-rail-preview').hidden`), false);
    await evaluate(`document.querySelector('.conversation-rail button').dispatchEvent(new KeyboardEvent('keydown',{key:'End',bubbles:true}))`);
    assert.match(await evaluate(`document.activeElement.ariaLabel`), /Question 129/);
    await evaluate(`document.activeElement.click()`); await wait(900);
    assert.ok(await evaluate(`document.getElementById('dcThread').scrollTop > 30000`));
    assert.equal(await evaluate(`document.querySelectorAll('.conversation-rail [aria-current="true"]').length`), 1);
    await evaluate(`window.lang='en-US';window.dispatchEvent(new Event('tools:languagechange'))`); await wait(150);
    assert.match(await evaluate(`document.querySelector('.conversation-rail').ariaLabel`), /Latest 100/);
    await evaluate(`fill(3)`); await wait(200);
    assert.equal(await evaluate(`document.querySelectorAll('.conversation-rail button').length`), 3);
    await win.setSize(390, 700); await wait(150);
    assert.ok(await evaluate(`document.querySelector('.conversation-rail-preview').hidden`));
    await evaluate(`document.documentElement.dataset.theme='dark';document.querySelector('.conversation-rail button').focus()`);
    assert.equal(await evaluate(`getComputedStyle(document.querySelector('.conversation-rail-preview')).backgroundColor`), 'rgb(40, 42, 47)');
    await evaluate(`fill(0)`); await wait(200);
    assert.equal(await evaluate(`document.querySelector('.conversation-rail').hidden`), true);
    console.log('PASS: bounded navigation, safe previews, keyboard, scrolling, language, session reset, narrow layout and dark theme');
}).then(() => { clearTimeout(timeout); win?.destroy(); fs.rmSync(temp, { recursive: true, force: true }); app.quit(); }).catch(error => { console.error(error); app.exit(1); });
