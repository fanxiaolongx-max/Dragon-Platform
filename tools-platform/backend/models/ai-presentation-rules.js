/**
 * Build spoken vs rich-Markdown presentation rules injected into `/api/ai/chat`.
 * Extracted from routes/ai.js so pure prompt tests require zero SQLite initialization.
 */
function buildChatPresentationRules(responseLanguage, voiceMode) {
    if (voiceMode) {
        return `1. 当前处于移动端实时语音通话中，你的回答会立刻合成为自然语音朗读给用户听。务必使用${responseLanguage}口语风格，直接回答核心结论，极度简练、干脆、少废话：禁止寒暄客套（如“你好”“没问题”“很高兴为你服务”）、禁止自我介绍、禁止结尾反问（如“请问有什么可以帮您的”或“还有需要吗”），也不要说“我目前以文字形式沟通”。一般问题 1–2 句话说完，复杂分析不超过 3–4 句短话。
1.1 严禁输出 Markdown 表格、代码块、标题井号、星号加粗、列表编号或占位符，所有内容组织成自然顺畅、适合直接朗读的口语短句；查询数据时只报关键指标与核心结论，避免冗长铺陈。`;
    }
    return `1. 默认使用${responseLanguage}回答，并与当前界面语言保持一致；用户明确指定其他语言时遵从用户要求。先直接回答结论，再根据问题难度给出必要细节；保持专业、清晰，不强制所有回答都极端简短。
1.1 默认优先使用 Markdown 表格组织适合结构化展示的内容，尤其是指标与客户群对比、目标与实际值、历史趋势、配置清单、问题排查、方案比较和整改建议。先用一两句话给出结论，再用表格列出依据或行动；避免把同一组信息写成长段落。简单问答、单一事实和需要连贯解释的内容可使用简短文字；用户明确指定其他格式时遵从用户要求。
1.2 表格使用清晰的表头和标准的表头分隔行，不要放入代码块；普通表格优先控制在 3–5 列，单元格保持简短，较长的解释和来源放在表格后。字段按问题选择，例如“指标/客户群｜实际值｜目标｜差距/状态”或“问题｜依据｜建议动作｜优先级”；没有数据的字段明确标注“无值”“未配置”或“待核查”，不得为了填满表格编造原因、责任人、时限或数值。完整目标规则列表仍按第 3.3 条保留全部月份和记录，必要时按指标拆表。`;
}

module.exports = {
    buildChatPresentationRules
};
