android {
    namespace = "com.example.newapp"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.example.newapp"
        minSdk = 24
        targetSdk = 35
        val runNumber = System.getenv("GITHUB_RUN_NUMBER")
        versionCode = System.getenv("APP_VERSION_CODE")?.toIntOrNull() ?: (runNumber?.toIntOrNull() ?: 4)
        versionName = System.getenv("APP_VERSION_NAME") ?: (if (runNumber != null) "1.1.$runNumber" else "1.1.0")

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            val keystorePath = System.getenv("ANDROID_KEYSTORE_PATH")
            if (keystorePath != null && file(keystorePath).exists()) {
                storeFile = file(keystorePath)
                storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD") ?: ""
                keyAlias = System.getenv("ANDROID_KEY_ALIAS") ?: ""
                keyPassword = System.getenv("ANDROID_KEY_PASSWORD") ?: ""
            } else {
                val fallbackStore = file(System.getProperty("user.home") + "/.android/debug.keystore")
                if (!fallbackStore.exists()) {
                    fallbackStore.parentFile.mkdirs()
                    try {
                        ProcessBuilder(
                            "keytool", "-genkey", "-v",
                            "-keystore", fallbackStore.absolutePath,
                            "-storepass", "android",
                            "-alias", "androiddebugkey",
                            "-keypass", "android",
                            "-keyalg", "RSA",
                            "-keysize", "2048",
                            "-validity", "10000",
                            "-dname", "CN=Android Debug,O=Android,C=US"
                        ).start().waitFor()
                    } catch (_: Exception) {}
                }
                if (fallbackStore.exists()) {
                    storeFile = fallbackStore
                    storePassword = "android"
                    keyAlias = "androiddebugkey"
                    keyPassword = "android"
                } else {
                    initWith(getByName("debug"))
                }
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.getByName("release")
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_21
        targetCompatibility = JavaVersion.VERSION_21
    }
    kotlinOptions {
        jvmTarget = "21"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
